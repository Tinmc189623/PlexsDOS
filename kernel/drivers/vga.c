/* ==================== 调色板操作 ==================== */

/*
 * gfx_set_palette_entry — 设置调色板条目
 * @index: 颜色索引 (0-255)
 * @r, @g, @b: RGB 分量 (0-63)
 */
void gfx_set_palette_entry(uint8_t index, uint8_t r, uint8_t g, uint8_t b)
{
    vga_wait_vsync();
    outb(VGA_DAC_WRITE, index);
    outb(VGA_DAC_DATA, r);
    outb(VGA_DAC_DATA, g);
    outb(VGA_DAC_DATA, b);
}

/*
 * gfx_set_default_palette — 设置 Windows 3.x 默认调色板
 *
 * 前 16 色为标准 VGA 颜色，后续条目可自定义。
 */
void gfx_set_default_palette(void)
{
    /* 标准 VGA 16 色调色板 (RGB 各 6 bit) */
    static const uint8_t palette[16][3] = {
        { 0,  0,  0},   /* 0: 黑 */
        { 0,  0, 42},   /* 1: 蓝 */
        { 0, 42,  0},   /* 2: 绿 */
        { 0, 42, 42},   /* 3: 青 */
        {42,  0,  0},   /* 4: 红 */
        {42,  0, 42},   /* 5: 品红 */
        {42, 21,  0},   /* 6: 棕 */
        {42, 42, 42},   /* 7: 浅灰 */
        {21, 21, 21},   /* 8: 深灰 */
        {21, 21, 63},   /* 9: 浅蓝 */
        {21, 63, 21},   /* 10: 浅绿 */
        {21, 63, 63},   /* 11: 浅青 */
        {63, 21, 21},   /* 12: 浅红 */
        {63, 21, 63},   /* 13: 浅品红 */
        {63, 63, 21},   /* 14: 黄 */
        {63, 63, 63}    /* 15: 白 */
    };
    int i;

    for (i = 0; i < 16; i++) {
        gfx_set_palette_entry((uint8_t)i,
                              palette[i][0],
                              palette[i][1],
                              palette[i][2]);
    }
}
