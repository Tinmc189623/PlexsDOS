/*
 * graphics_init — 初始化 VGA 图形模式
 * @mode: VGA 模式号 (VGA_MODE_12H 或 VGA_MODE_13H)
 * 返回: true = 成功
 */
bool graphics_init(uint8_t mode)
{
    if (mode != VGA_MODE_12H && mode != VGA_MODE_13H)
        return false;

    vga_load_mode(mode);
    g_current_mode = mode;

    if (mode == VGA_MODE_12H) {
        g_screen_width = VGA12_WIDTH;
        g_screen_height = VGA12_HEIGHT;
        g_framebuffer = (uint8_t *)VGA12_FB_ADDR;
    } else {
        g_screen_width = VGA13_WIDTH;
        g_screen_height = VGA13_HEIGHT;
        g_framebuffer = (uint8_t *)VGA13_FB_ADDR;
    }

    return true;
}

/*
 * graphics_restore — 恢复文本模式
 */
void graphics_restore(void)
{
    /* 使用 BIOS int 0x10 恢复模式 0x03 */
    /* 在保护模式下直接设置 VGA 寄存器 */
    static const uint8_t text_seq[] = {0x03, 0x00, 0x03, 0x00, 0x02};
    static const uint8_t text_crtc[] = {
        0x5F, 0x4F, 0x50, 0x82, 0x55, 0x81, 0xBF, 0x1F,
        0x00, 0x4F, 0x0D, 0x0E, 0x00, 0x00, 0x00, 0x00,
        0x9C, 0x8E, 0x8F, 0x28, 0x1F, 0x96, 0xB9, 0xA3,
        0xFF
    };
    static const uint8_t text_gc[] = {0x00, 0x00, 0x00, 0x00, 0x00, 0x10, 0x0E, 0x00, 0xFF};
    static const uint8_t text_ac[] = {
        0x00, 0x01, 0x02, 0x03, 0x04, 0x05, 0x14, 0x07,
        0x38, 0x39, 0x3A, 0x3B, 0x3C, 0x3D, 0x3E, 0x3F,
        0x0C, 0x00, 0x0F, 0x08, 0x00
    };
    int i;

    outb(VGA_MISC_OUT, 0x67);

    for (i = 0; i < 5; i++)
        vga_seq_write(i, text_seq[i]);

    vga_crtc_write(0x11, text_crtc[0x11] & 0x7F);
    for (i = 0; i < 25; i++)
        vga_crtc_write(i, text_crtc[i]);

    for (i = 0; i < 9; i++)
        vga_gc_write(i, text_gc[i]);

    for (i = 0; i < 21; i++)
        vga_ac_write(i, text_ac[i]);

    g_current_mode = VGA_MODE_TEXT;
}

