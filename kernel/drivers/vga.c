/*
 * gfx_draw_bitmap — 绘制位图
 * @x, @y: 左上角坐标
 * @bmp:   位图指针
 *
 * 位图数据格式: 每像素 4 bit (Mode 12h 颜色索引)，打包存储。
 * 每字节存储 2 个像素，高 nibble 在左。
 */
void gfx_draw_bitmap(int x, int y, const struct bitmap *bmp)
{
    int row, col;
    uint8_t byte;

    if (!bmp || !bmp->data)
        return;

    for (row = 0; row < bmp->height; row++) {
        for (col = 0; col < bmp->width; col++) {
            byte = bmp->data[(row * bmp->width + col) / 2];
            if (col & 1)
                gfx_put_pixel(x + col, y + row, byte & 0x0F);
            else
                gfx_put_pixel(x + col, y + row, (byte >> 4) & 0x0F);
        }
    }
}

