/* ==================== 基础图形原语 ==================== */

/*
 * gfx_put_pixel — 画点
 * @x, @y: 坐标
 * @color: 颜色
 *
 * Mode 12h: 4 平面模式，每个平面存储一个位。
 *           像素地址 = y * 80 + x / 8，位 = 7 - (x % 8)
 * Mode 13h: 线性帧缓冲，像素地址 = y * 320 + x
 */
void gfx_put_pixel(int x, int y, uint8_t color)
{
    if (x < 0 || y < 0 || x >= g_screen_width || y >= g_screen_height)
        return;

    if (g_current_mode == VGA_MODE_12H) {
        uint16_t offset = (uint16_t)(y * 80 + (x >> 3));
        uint8_t bit = 0x80 >> (x & 7);
        uint8_t plane;

        /* 设置位掩码: 只修改目标像素 */
        vga_set_bitmask(bit);

        /* 对每个平面，写入颜色的对应位 */
        for (plane = 0; plane < 4; plane++) {
            vga_set_plane(plane);
            /* 读取锁存器（触发锁存） */
            (void)g_framebuffer[offset];
            /* 写入: 如果该平面对应颜色位为1则全1，否则全0 */
            g_framebuffer[offset] = (color & (1 << plane)) ? 0xFF : 0x00;
        }

        /* 恢复位掩码 */
        vga_set_bitmask(0xFF);
        vga_set_plane(0x0F);
    } else {
        /* Mode 13h: 线性帧缓冲 */
        g_framebuffer[(uint32_t)y * VGA13_WIDTH + x] = color;
    }
}

/*
 * gfx_get_pixel — 读取点颜色
 * @x, @y: 坐标
 * 返回: 颜色值
 */
uint8_t gfx_get_pixel(int x, int y)
{
    if (x < 0 || y < 0 || x >= g_screen_width || y >= g_screen_height)
        return 0;

    if (g_current_mode == VGA_MODE_12H) {
        uint16_t offset = (uint16_t)(y * 80 + (x >> 3));
        uint8_t bit = 0x80 >> (x & 7);
        uint8_t color = 0;
        uint8_t plane;

        /* 设置读取位掩码 */
        vga_set_bitmask(bit);

        for (plane = 0; plane < 4; plane++) {
            vga_set_read_plane(plane);
            if (g_framebuffer[offset] & bit)
                color |= (1 << plane);
        }

        vga_set_bitmask(0xFF);
        return color;
    } else {
        return g_framebuffer[(uint32_t)y * VGA13_WIDTH + x];
    }
}

/*
 * gfx_draw_hline — 画水平线
 * @x, @y: 起点
 * @len:   长度
 * @color: 颜色
 */
void gfx_draw_hline(int x, int y, int len, uint8_t color)
{
    int i;
    if (y < 0 || y >= g_screen_height)
        return;
    for (i = 0; i < len; i++)
        gfx_put_pixel(x + i, y, color);
}

/*
 * gfx_draw_vline — 画垂直线
 * @x, @y: 起点
 * @len:   长度
 * @color: 颜色
 */
void gfx_draw_vline(int x, int y, int len, uint8_t color)
{
    int i;
    if (x < 0 || x >= g_screen_width)
        return;
    for (i = 0; i < len; i++)
        gfx_put_pixel(x, y + i, color);
}

/*
 * gfx_draw_line — 画任意直线 (Bresenham 算法)
 * @x1, @y1: 起点
 * @x2, @y2: 终点
 * @color:   颜色
 */
void gfx_draw_line(int x1, int y1, int x2, int y2, uint8_t color)
{
    int dx, dy, sx, sy, err, e2;

    dx = (x2 > x1) ? (x2 - x1) : (x1 - x2);
    dy = (y2 > y1) ? (y2 - y1) : (y1 - y2);
    sx = (x1 < x2) ? 1 : -1;
    sy = (y1 < y2) ? 1 : -1;
    err = dx - dy;

    for (;;) {
        gfx_put_pixel(x1, y1, color);
        if (x1 == x2 && y1 == y2)
            break;
        e2 = 2 * err;
        if (e2 > -dy) {
            err -= dy;
            x1 += sx;
        }
        if (e2 < dx) {
            err += dx;
            y1 += sy;
        }
    }
}

/*
 * gfx_draw_rect — 画矩形边框
 * @x, @y:       左上角
 * @width, @height: 尺寸
 * @color:       颜色
 */
void gfx_draw_rect(int x, int y, int width, int height, uint8_t color)
{
    gfx_draw_hline(x, y, width, color);
    gfx_draw_hline(x, y + height - 1, width, color);
    gfx_draw_vline(x, y, height, color);
    gfx_draw_vline(x + width - 1, y, height, color);
}

/*
 * gfx_fill_rect — 填充矩形
 * @x, @y:       左上角
 * @width, @height: 尺寸
 * @color:       颜色
 *
 * Mode 12h 优化: 使用位掩码和锁存器批量写入整字节像素。
 * Mode 13h: 使用 memset 批量填充。
 */
void gfx_fill_rect(int x, int y, int width, int height, uint8_t color)
{
    int row, col;

    if (width <= 0 || height <= 0)
        return;

    if (g_current_mode == VGA_MODE_13H) {
        /* Mode 13h: 线性帧缓冲优化 */
        for (row = 0; row < height; row++) {
            int sy = y + row;
            if (sy < 0 || sy >= g_screen_height)
                continue;
            int sx = x;
            int len = width;
            if (sx < 0) { len += sx; sx = 0; }
            if (sx + len > VGA13_WIDTH) len = VGA13_WIDTH - sx;
            if (len > 0) {
                memset(&g_framebuffer[(uint32_t)sy * VGA13_WIDTH + sx], color, (size_t)len);
            }
        }
    } else {
        /* Mode 12h: 逐像素写入 */
        for (row = 0; row < height; row++) {
            for (col = 0; col < width; col++) {
                gfx_put_pixel(x + col, y + row, color);
            }
        }
    }
}

/*
 * gfx_draw_circle — 画圆 (中点圆算法)
 * @cx, @cy: 圆心
 * @radius:  半径
 * @color:   颜色
 */
void gfx_draw_circle(int cx, int cy, int radius, uint8_t color)
{
    int x = 0;
    int y = radius;
    int d = 1 - radius;

    while (x <= y) {
        /* 8 对称点 */
        gfx_put_pixel(cx + x, cy + y, color);
        gfx_put_pixel(cx - x, cy + y, color);
        gfx_put_pixel(cx + x, cy - y, color);
        gfx_put_pixel(cx - x, cy - y, color);
        gfx_put_pixel(cx + y, cy + x, color);
        gfx_put_pixel(cx - y, cy + x, color);
        gfx_put_pixel(cx + y, cy - x, color);
        gfx_put_pixel(cx - y, cy - x, color);

        if (d < 0) {
            d += 2 * x + 3;
        } else {
            d += 2 * (x - y) + 5;
            y--;
        }
        x++;
    }
}

/*
 * gfx_fill_circle — 填充圆
 * @cx, @cy: 圆心
 * @radius:  半径
 * @color:   颜色
 */
void gfx_fill_circle(int cx, int cy, int radius, uint8_t color)
{
    int x = 0;
    int y = radius;
    int d = 1 - radius;

    while (x <= y) {
        /* 画水平扫描线填充 */
        gfx_draw_hline(cx - x, cy + y, 2 * x + 1, color);
        gfx_draw_hline(cx - x, cy - y, 2 * x + 1, color);
        gfx_draw_hline(cx - y, cy + x, 2 * y + 1, color);
        gfx_draw_hline(cx - y, cy - x, 2 * y + 1, color);

        if (d < 0) {
            d += 2 * x + 3;
        } else {
            d += 2 * (x - y) + 5;
            y--;
        }
        x++;
    }
}

/* ==================== 文本渲染 ==================== */

/*
 * gfx_draw_char — 绘制单个字符
 * @x, @y:  左上角坐标
 * @c:      字符
 * @fg:     前景色
 * @bg:     背景色
 *
 * 使用 VGA 标准 8x16 位图字体。
 */
void gfx_draw_char(int x, int y, char c, uint8_t fg, uint8_t bg)
{
    const uint8_t *glyph;
    int row, col;
    uint8_t bits;

    if (c < 32 || c > 127)
        c = '?';  /* 不可打印字符用 ? 代替 */

    glyph = vga_font_8x16[(int)c - 32];

    for (row = 0; row < FONT_HEIGHT; row++) {
        bits = glyph[row];
        for (col = 0; col < FONT_WIDTH; col++) {
            if (bits & (0x80 >> col))
                gfx_put_pixel(x + col, y + row, fg);
            else
                gfx_put_pixel(x + col, y + row, bg);
        }
    }
}

/*
 * gfx_draw_string — 绘制字符串
 * @x, @y:  左上角坐标
 * @str:    字符串
 * @fg:     前景色
 * @bg:     背景色
 */
void gfx_draw_string(int x, int y, const char *str, uint8_t fg, uint8_t bg)
{
    int cx = x;
    while (*str) {
        if (*str == '\n') {
            cx = x;
            y += FONT_HEIGHT;
        } else {
            gfx_draw_char(cx, y, *str, fg, bg);
            cx += FONT_WIDTH;
        }
        str++;
    }
}

/*
 * gfx_draw_string_transparent — 绘制透明背景字符串
 * @x, @y:  左上角坐标
 * @str:    字符串
 * @fg:     前景色 (背景不绘制)
 */
void gfx_draw_string_transparent(int x, int y, const char *str, uint8_t fg)
{
    const uint8_t *glyph;
    int cx = x;
    int row, col;
    uint8_t bits;

    while (*str) {
        if (*str == '\n') {
            cx = x;
            y += FONT_HEIGHT;
        } else {
            char c = *str;
            if (c < 32 || c > 127)
                c = '?';
            glyph = vga_font_8x16[(int)c - 32];
            for (row = 0; row < FONT_HEIGHT; row++) {
                bits = glyph[row];
                for (col = 0; col < FONT_WIDTH; col++) {
                    if (bits & (0x80 >> col))
                        gfx_put_pixel(cx + col, y + row, fg);
                }
            }
            cx += FONT_WIDTH;
        }
        str++;
    }
}

