/* ==================== 内部辅助函数 ==================== */

/*
 * vga_seq_write — 写 Sequencer 寄存器
 */
static void vga_seq_write(uint8_t index, uint8_t value)
{
    outb(VGA_SEQ_ADDR, index);
    outb(VGA_SEQ_DATA, value);
}

/*
 * vga_crtc_write — 写 CRTC 寄存器
 */
static void vga_crtc_write(uint8_t index, uint8_t value)
{
    outb(VGA_CRTC_ADDR, index);
    outb(VGA_CRTC_DATA, value);
}

/*
 * vga_gc_write — 写 Graphics Controller 寄存器
 */
static void vga_gc_write(uint8_t index, uint8_t value)
{
    outb(VGA_GC_ADDR, index);
    outb(VGA_GC_DATA, value);
}

/*
 * vga_ac_write — 写 Attribute Controller 寄存器
 * 注意: 需要先读 Input Status 寄存器来重置 AC 索引
 */
static void vga_ac_write(uint8_t index, uint8_t value)
{
    (void)inb(VGA_INPUT_STATUS);  /* 重置 AC 索引 */
    outb(VGA_AC_ADDR, index | 0x20);
    outb(VGA_AC_ADDR, value);
}

/*
 * vga_wait_vsync — 等待垂直同步
 * 用于减少切换调色板时的闪烁
 */
static void vga_wait_vsync(void)
{
    while (inb(VGA_INPUT_STATUS) & 0x08)
        ;
    while (!(inb(VGA_INPUT_STATUS) & 0x08))
        ;
}

/*
 * vga_load_mode — 加载 VGA 模式寄存器
 * @mode: 模式号 (VGA_MODE_12H 或 VGA_MODE_13H)
 */
static void vga_load_mode(uint8_t mode)
{
    const uint8_t *seq, *crtc, *gc, *ac;
    int i;

    if (mode == VGA_MODE_12H) {
        seq = seq_regs_12h;
        crtc = crtc_regs_12h;
        gc = gc_regs_12h;
        ac = ac_regs_12h;
    } else {
        seq = seq_regs_13h;
        crtc = crtc_regs_13h;
        gc = gc_regs_13h;
        ac = ac_regs_13h;
    }

    /* Miscellaneous Output */
    outb(VGA_MISC_OUT, 0xE3);

    /* Sequencer */
    for (i = 0; i < 5; i++)
        vga_seq_write(i, seq[i]);

    /* CRTC (解锁) */
    vga_crtc_write(0x11, crtc[0x11] & 0x7F);
    for (i = 0; i < 25; i++)
        vga_crtc_write(i, crtc[i]);

    /* Graphics Controller */
    for (i = 0; i < 9; i++)
        vga_gc_write(i, gc[i]);

    /* Attribute Controller */
    for (i = 0; i < 21; i++)
        vga_ac_write(i, ac[i]);
}

/*
 * vga_set_plane — 选择写入平面 (Mode 12h)
 * @plane: 平面号 (0-3)
 */
static void vga_set_plane(uint8_t plane)
{
    vga_seq_write(SEQ_MAP_MASK, 1 << plane);
}

/*
 * vga_set_read_plane — 选择读取平面 (Mode 12h)
 * @plane: 平面号 (0-3)
 */
static void vga_set_read_plane(uint8_t plane)
{
    vga_gc_write(GC_READ_MAP, plane);
}

/*
 * vga_set_bitmask — 设置位掩码 (Mode 12h)
 * 用于控制写入时哪些位被修改
 */
static void vga_set_bitmask(uint8_t mask)
{
    vga_gc_write(GC_BIT_MASK, mask);
}

