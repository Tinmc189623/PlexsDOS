/*
 * x12_write_pixel — 写入像素到后缓冲区
 * @x, @y: 坐标
 * @color: 32-bit ARGB 颜色
 */
static void x12_write_pixel(int x, int y, uint32_t color)
{
    if (x < 0 || x >= screen_width || y < 0 || y >= screen_height)
        return;
    backbuffer[y * screen_width + x] = color;
}

