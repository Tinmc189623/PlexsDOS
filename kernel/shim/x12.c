static uint32_t x12_read_pixel(int x, int y)
{
    if (x < 0 || x >= screen_width || y < 0 || y >= screen_height)
        return 0;
    return backbuffer[y * screen_width + x];
}

/*
 * x12_clip_check — 检查坐标是否在裁剪区域内
 * @win:  窗口指针 (NULL = 全屏)
 * @x, @y: 坐标
 * 返回: true = 可见
 */
static bool x12_is_visible(struct x12_window *win, int x, int y)
{
    if (!win)
        return (x >= 0 && x < screen_width && y >= 0 && y < screen_height);

    if (!win->mapped)
        return false;

    if (win->clip_enabled) {
        return (x >= win->clip_x && x < win->clip_x + win->clip_w &&
                y >= win->clip_y && y < win->clip_y + win->clip_h);
    }

    return (x >= win->x && x < win->x + win->width &&
            y >= win->y && y < win->y + win->height);
}

/*
 * x12_push_event — 压入事件到队列
 */
static void x12_push_event(struct x12_event *ev)
{
    if (event_count >= X12_EVENT_QUEUE_SIZE)
        return;

    event_queue[event_tail] = *ev;
    event_tail = (event_tail + 1) % X12_EVENT_QUEUE_SIZE;
    event_count++;
}

/* ==================== 公共 API ==================== */

bool x12_init(int width, int height)
{
    if (x12_initialized)
        return true;

    screen_width = width;
    screen_height = height;

    /* 映射 VBE LFB */
    lfb = (uint32_t *)VBE_LFB_ADDR;

    /* 检查 VBE 是否激活 (读第一个像素非 0xFFFF) */
    volatile uint32_t test = lfb[0];
    (void)test;

    /* 清空后缓冲区 */
    for (int i = 0; i < screen_width * screen_height; i++)
        backbuffer[i] = X12_PIXEL_BLACK;

    /* 初始化窗口表 */
    for (int i = 0; i < X12_MAX_WINDOWS; i++) {
        windows[i].mapped = 0;
    }
    window_count = 0;

    /* 重置事件队列 */
    event_head = 0;
    event_tail = 0;
    event_count = 0;

    x12_initialized = 1;

    /* 清除屏幕为深蓝色 (Windows NT 风格) */
    x12_clear_screen(0xFF008000);
    x12_flush();

    return true;
}

void x12_shutdown(void)
{
    if (!x12_initialized) return;
    x12_initialized = 0;
}

struct x12_window *x12_create_window(int x, int y, int width, int height,
                                      const char *title)
{
    if (!x12_initialized)
        return NULL;

    if (window_count >= X12_MAX_WINDOWS)
        return NULL;

    struct x12_window *win = &windows[window_count];
    win->x = x;
    win->y = y;
    win->width = width;
    win->height = height;
    win->mapped = 0;
    win->clip_enabled = 0;

    int i;
    for (i = 0; title && title[i] && i < 63; i++)
        win->title[i] = title[i];
    win->title[i] = '\0';

    window_count++;
    return win;
}

void x12_destroy_window(struct x12_window *win)
{
    if (!win) return;
    win->mapped = 0;

    /* 从列表中移除 (简单标记) */
    for (int i = 0; i < X12_MAX_WINDOWS; i++) {
        if (&windows[i] == win) {
            windows[i].mapped = 0;
            windows[i].width = 0;
            break;
        }
    }
}

void x12_map_window(struct x12_window *win)
{
    if (!win) return;
    win->mapped = 1;
    win->clip_enabled = 0;

    /* 填充窗口背景 */
    x12_fill_rect(win, 0, 0, win->width, win->height, X12_PIXEL_WHITE);

    /* 绘制标题栏 (Windows NT 风格深蓝) */
    x12_fill_rect(win, 0, 0, win->width, 20, X12_PIXEL_DARK_BLUE);

    /* 绘制标题文字 */
    int tx = (win->width - x12_get_text_width(win->title)) / 2;
    if (tx < 2) tx = 2;
    x12_draw_string(win, tx, 2, win->title, X12_PIXEL_WHITE);

    /* 绘制窗口边框 (深灰色) */
    x12_fill_rect(win, 0, 0, win->width, 1, 0xFF808080);
    x12_fill_rect(win, 0, win->height - 1, win->width, 1, 0xFF808080);
    x12_fill_rect(win, 0, 0, 1, win->height, 0xFF808080);
    x12_fill_rect(win, win->width - 1, 0, 1, win->height, 0xFF808080);

    x12_flush();
}

void x12_unmap_window(struct x12_window *win)
{
    if (!win) return;
    win->mapped = 0;
}

void x12_fill_rect(struct x12_window *win, int x, int y,
                    int w, int h, uint32_t color)
{
    if (!x12_initialized) return;

    for (int r = 0; r < h; r++) {
        for (int c = 0; c < w; c++) {
            int px = (win ? win->x : 0) + x + c;
            int py = (win ? win->y : 0) + y + r;
            if (x12_is_visible(win, px, py))
                x12_write_pixel(px, py, color);
        }
    }
}

void x12_draw_char(struct x12_window *win, int x, int y,
                    char c, uint32_t color)
{
    if (!x12_initialized) return;

    int win_x = win ? win->x : 0;
    int win_y = win ? win->y : 0;

    /* 只支持 ASCII 可打印字符 */
    if (c < 0x20 || c > 0x7E) {
        if (c == 0) return;
        c = '.'; /* 不可打印字符显示为点 */
    }

    const unsigned char *glyph = font8x16[c - 0x20];
    for (int row = 0; row < 16; row++) {
        for (int col = 0; col < 8; col++) {
            if (glyph[row] & (1 << (7 - col))) {
                int px = win_x + x + col;
                int py = win_y + y + row;
                if (x12_is_visible(win, px, py))
                    x12_write_pixel(px, py, color);
            }
        }
    }
}

void x12_draw_string(struct x12_window *win, int x, int y,
                      const char *str, uint32_t color)
{
    if (!x12_initialized || !str) return;

    int cx = x;
    while (*str) {
        if (*str == '\n') {
            cx = x;
            y += 16;
        } else {
            x12_draw_char(win, cx, y, *str, color);
            cx += 8;
        }
        str++;
    }
}

int x12_get_text_width(const char *str)
{
    if (!str) return 0;
    int len = 0;
    while (str[len]) len++;
    return len * 8;
}

int x12_get_text_height(void)
{
    return 16;
}

void x12_draw_button(struct x12_window *win, int x, int y,
                      int w, int h, const char *text, bool pressed)
{
    if (!x12_initialized) return;

    /* 按钮背景 */
    uint32_t bg = pressed ? 0xFF808080 : 0xFFE0E0E0;
    uint32_t border_top = pressed ? 0xFF000000 : 0xFFFFFFFF;
    uint32_t border_bottom = pressed ? 0xFFFFFFFF : 0xFF808080;
    uint32_t border_left = pressed ? 0xFF000000 : 0xFFFFFFFF;
    uint32_t border_right = pressed ? 0xFFFFFFFF : 0xFF808080;

    x12_fill_rect(win, x, y, w, h, bg);

    /* 边框 - 3D 效果 */
    /* 上/左: 亮色 (未按下) 或 暗色 (按下) */
    x12_fill_rect(win, x, y, w, 1, border_top);
    x12_fill_rect(win, x, y, 1, h, border_left);
    /* 下/右: 暗色 (未按下) 或 亮色 (按下) */
    x12_fill_rect(win, x, y + h - 1, w, 1, border_bottom);
    x12_fill_rect(win, x + w - 1, y, 1, h, border_right);

    /* 文字居中 */
    int tw = x12_get_text_width(text);
    int tx = x + (w - tw) / 2;
    int ty = y + (h - 16) / 2;
    if (pressed) { tx++; ty++; }

    x12_draw_string(win, tx, ty, text, 0xFF000000);
}

void x12_draw_progress_bar(struct x12_window *win, int x, int y,
                            int w, int h, int percent)
{
    if (!x12_initialized) return;

    if (percent < 0) percent = 0;
    if (percent > 100) percent = 100;

    /* 边框 */
    x12_fill_rect(win, x, y, w, h, 0xFF000000);
    x12_fill_rect(win, x + 1, y + 1, w - 2, h - 2, 0xFFFFFFFF);

    /* 填充 */
    int fill_w = ((w - 4) * percent) / 100;
    if (fill_w > 0) {
        for (int r = 0; r < h - 4; r++) {
            /* 渐变效果: 上浅下深 */
            uint32_t color;
            if (r < (h - 4) / 2)
                color = 0xFF60C0FF;  /* 亮蓝 */
            else
                color = 0xFF2080E0;  /* 深蓝 */
            x12_fill_rect(win, x + 2, y + 2 + r, fill_w, 1, color);
        }
    }

    /* 百分比文字 */
    char pct_str[8];
    int pct_len = 0;
    if (percent >= 100) { pct_str[0] = '1'; pct_str[1] = '0'; pct_str[2] = '0'; pct_str[3] = '%'; pct_str[4] = '\0'; }
    else if (percent >= 10) { pct_str[0] = '0' + percent/10; pct_str[1] = '0' + percent%10; pct_str[2] = '%'; pct_str[3] = '\0'; }
    else { pct_str[0] = '0' + percent; pct_str[1] = '%'; pct_str[2] = '\0'; }

    int tw = x12_get_text_width(pct_str);
    int tx = x + (w - tw) / 2;
    int ty = y + (h - 16) / 2;
    x12_draw_string(win, tx, ty, pct_str, 0xFF000000);
}

bool x12_next_event(struct x12_window *win, struct x12_event *event)
{
    if (!x12_initialized || !event)
        return false;

    /* 先轮询键盘 */
    if (keyboard_available()) {
        char c = keyboard_getchar();

        /* 构造键盘事件, 模拟 X11 keycode */
        int keycode = 0;
        if (c >= 'a' && c <= 'z')
            keycode = 0x1E + (c - 'a');
        else if (c >= '0' && c <= '9')
            keycode = 0x0B + (c - '0');
        else if (c == '\r' || c == '\n')
            keycode = 0x1C;
        else if (c == '\b')
            keycode = 0x0E;
        else if (c == '\t')
            keycode = 0x0F;
        else if (c == ' ')
            keycode = 0x39;

        event->type = X12_EVENT_KEY_DOWN;
        event->key.keycode = keycode;
        event->key.ascii = c;
        return true;
    }

    /* 然后检查事件队列 */
    if (event_count > 0) {
        *event = event_queue[event_head];
        event_head = (event_head + 1) % X12_EVENT_QUEUE_SIZE;
        event_count--;
        return true;
    }

    return false;
}

bool x12_poll_event(struct x12_window *win, struct x12_event *event)
{
    return x12_next_event(win, event);
}

void x12_flush(void)
{
    if (!x12_initialized || !lfb)
        return;

    /* 复制后缓冲区到 LFB */
    /* 使用 32-bit 复制 (4 字节) */
    for (int i = 0; i < screen_width * screen_height; i++)
        lfb[i] = backbuffer[i];
}

void x12_clear_screen(uint32_t color)
{
    if (!x12_initialized) return;

    for (int i = 0; i < screen_width * screen_height; i++)
        backbuffer[i] = color;
}

int x12_get_width(void)
{
    return screen_width;
}

int x12_get_height(void)
{
    return screen_height;
}

int x12_run_modal(struct x12_window *win, const char **buttons)
{
    if (!x12_initialized || !win || !buttons)
        return -1;

    /* 计算按钮位置 (居中排列) */
    int num_buttons = 0;
    while (buttons[num_buttons]) num_buttons++;

    if (num_buttons == 0) return -1;

    /* 按钮尺寸 */
    int btn_w = 100, btn_h = 28;
    int gap = 12;
    int total_w = num_buttons * btn_w + (num_buttons - 1) * gap;
    int start_x = (win->width - total_w) / 2;
    int btn_y = win->height - 48;

    /* 绘制按钮 */
    int btn_x[X12_MAX_WINDOWS];
    for (int i = 0; i < num_buttons && i < X12_MAX_WINDOWS; i++) {
        btn_x[i] = start_x + i * (btn_w + gap);
        x12_draw_button(win, btn_x[i], btn_y, btn_w, btn_h, buttons[i], false);
    }
    x12_flush();

    /* 事件循环 */
    int focused = 0;  /* 当前焦点按钮 */
    while (1) {
        struct x12_event ev;
        if (x12_next_event(win, &ev)) {
            if (ev.type == X12_EVENT_KEY_DOWN) {
                if (ev.key.keycode == 0x1C) {  /* Enter */
                    return focused;
                }
                if (ev.key.keycode == 0x0F) {  /* Tab */
                    focused = (focused + 1) % num_buttons;
                    /* 重绘按钮焦点 */
                    for (int i = 0; i < num_buttons; i++) {
                        x12_draw_button(win, btn_x[i], btn_y, btn_w, btn_h,
                                        buttons[i], i == focused);
                    }
                    x12_flush();
                }
                if (ev.key.keycode == 0x0E) {  /* Backspace / ESC */
                    return -1;
                }
                /* 左右箭头切换焦点 */
                if (ev.key.ascii == 0x4B || ev.key.ascii == 0x44) {  /* Left */
                    focused = (focused > 0) ? focused - 1 : num_buttons - 1;
                    for (int i = 0; i < num_buttons; i++) {
                        x12_draw_button(win, btn_x[i], btn_y, btn_w, btn_h,
                                        buttons[i], i == focused);
                    }
                    x12_flush();
                }
                if (ev.key.ascii == 0x4D || ev.key.ascii == 0x43) {  /* Right */
                    focused = (focused + 1) % num_buttons;
                    for (int i = 0; i < num_buttons; i++) {
                        x12_draw_button(win, btn_x[i], btn_y, btn_w, btn_h,
                                        buttons[i], i == focused);
                    }
                    x12_flush();
                }
            }
        }
    }

    return -1;
}

void x12_set_clip_rect(struct x12_window *win, int x, int y, int w, int h)
{
    if (!win) return;
    win->clip_enabled = 1;
    win->clip_x = win->x + x;
    win->clip_y = win->y + y;
    win->clip_w = w;
    win->clip_h = h;
}
